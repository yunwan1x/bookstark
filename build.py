#!/usr/bin/env python3
import datetime
import argparse
import os
import subprocess
import re
import hashlib


def file_md5(filepath):
    """Compute MD5 hex digest of a file."""
    h = hashlib.md5()
    with open(filepath, 'rb') as f:
        for chunk in iter(lambda: f.read(8192), b''):
            h.update(chunk)
    return h.hexdigest()


def sw_logic_md5(filepath):
    """Hash the hand-maintained service worker logic without generated fields."""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    content = re.sub(r"const STATIC_CACHE = 'bookstark-static-[^']*'", "const STATIC_CACHE = 'bookstark-static-__HASH__'", content)
    content = re.sub(r"const DYNAMIC_CACHE = 'bookstark-dynamic-[^']*'", "const DYNAMIC_CACHE = 'bookstark-dynamic-v1'", content)
    content = re.sub(r'const STATIC_ASSETS = \[[\s\S]*?\];', 'const STATIC_ASSETS = [__ASSETS__];', content)
    content = re.sub(r'// .+? — auto-generated by build\.py', '// __HASH__ — auto-generated by build.py', content, count=1)
    return hashlib.md5(content.encode('utf-8')).hexdigest()


def should_precache(rel):
    """Return whether an asset belongs in the install-time cache."""
    # Univer is loaded only for spreadsheet documents and its browser bundle is
    # large. Let the runtime cache it after first use instead of delaying every
    # service-worker installation.
    if rel.startswith('static/js/univer/'):
        return False
    # PPTist is a full presentation application with optional CJK fonts. It is
    # loaded only for presentation documents and must not block PWA installs.
    if rel.startswith('static/pptist/'):
        return False
    # Three.js is loaded only when a WebRTC host explicitly enters the optional
    # 3D meeting-room scene. Runtime-cache it instead of delaying every install.
    if rel.startswith('static/vendor/three/'):
        return False
    return True


def scan_static_assets(static_dir):
    """Scan static/ directory and return (assets_list, combined_hash, file_hashes).

    assets_list: ordered list of versioned asset URLs (per-file MD5 for ?v=)
    combined_hash: MD5 of all file contents concatenated (for STATIC_CACHE name)
    file_hashes: dict of rel_path -> md5hex (used by Go for template ?v=)
    """
    icons = []
    css = []
    js = []
    fonts = []
    html = []

    file_hashes = {}
    hash_feed = hashlib.md5()

    for root, dirs, files in os.walk(static_dir):
        # Skip hidden dirs
        dirs[:] = [d for d in dirs if not d.startswith('.')]
        for f in sorted(files):
            if f.startswith('.'):
                continue
            rel = os.path.join(root, f).replace(os.sep, '/')
            ext = f.rsplit('.', 1)[-1].lower() if '.' in f else ''

            # asset-hashes.json is generated and depends on the hash — exclude to avoid circular dependency
            if rel == 'static/asset-hashes.json':
                continue

            # Compute per-file hash
            fhash = sw_logic_md5(rel) if rel == 'static/sw.js' else file_md5(rel)
            file_hashes[rel] = fhash

            # Feed into combined hash
            hash_feed.update(fhash.encode())

            # sw.js is appended once below with the combined hash as its version.
            if rel == 'static/sw.js':
                continue

            if not should_precache(rel):
                continue

            # Top-level icons and manifest
            if rel.startswith('static/') and ext in ('svg', 'png', 'ico') and '/css/' not in rel and '/js/' not in rel and '/webfonts/' not in rel and '/fonts/' not in rel:
                icons.append(rel)
            elif rel.startswith('static/') and f == 'manifest.json':
                icons.append(rel)
            elif ext == 'css':
                css.append(rel)
            elif ext == 'js':
                js.append(rel)
            elif ext in ('woff2', 'woff', 'ttf', 'otf'):
                fonts.append(rel)
            elif ext == 'html':
                html.append(rel)

    combined_hash = hash_feed.hexdigest()[:12]

    assets = []
    for a in icons + css + js + html:
        h = file_hashes[a][:8]
        assets.append(f"  '/{a}?v={h}'")
    # sw.js uses combined_hash as its version (since it's generated from all other files)
    assets.append(f"  '/static/sw.js?v={combined_hash[:8]}'")
    for a in fonts:
        assets.append(f"  '/{a}'")

    return assets, combined_hash, file_hashes


def patch_swjs(sw_path, static_hash, assets):
    """Read sw.js, replace cache names and STATIC_ASSETS block, write back."""
    with open(sw_path, 'r') as f:
        content = f.read()

    # Replace static cache name with content hash
    content = re.sub(
        r"const STATIC_CACHE = 'bookstark-static-[^']*'",
        f"const STATIC_CACHE = 'bookstark-static-{static_hash}'",
        content
    )

    # Replace dynamic cache with stable version
    content = re.sub(
        r"const DYNAMIC_CACHE = 'bookstark-dynamic-[^']*'",
        "const DYNAMIC_CACHE = 'bookstark-dynamic-v1'",
        content
    )

    # Replace the entire STATIC_ASSETS block
    assets_str = ',\n'.join(assets)
    content = re.sub(
        r'const STATIC_ASSETS = \[[\s\S]*?\];',
        f'const STATIC_ASSETS = [\n{assets_str}\n];',
        content
    )

    # Remove old comment or update it
    content = re.sub(
        r'// .+? — auto-generated by build\.py',
        f'// {static_hash} — auto-generated by build.py',
        content,
        count=1
    )

    with open(sw_path, 'w') as f:
        f.write(content)

    return len(assets)


def main(build_only=False, extra_args=None, output=None, goos=None, goarch=None):
    # Version info
    built = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=8))).strftime('%Y%m%d%H%M%S')
    commit = os.environ.get('COMMIT', '').strip()
    if not commit:
        try:
            commit = subprocess.check_output(
                ['git', 'rev-parse', 'HEAD'], text=True, stderr=subprocess.DEVNULL
            ).strip()
            if subprocess.check_output(['git', 'status', '--porcelain'], text=True).strip():
                commit += '-dirty'
        except (OSError, subprocess.CalledProcessError):
            commit = 'unknown'
    if not re.fullmatch(r'(?:[0-9a-fA-F]{7,40}(?:-dirty)?|unknown)', commit):
        raise ValueError('COMMIT must be a Git commit hash (optionally suffixed with -dirty)')
    go_ver = subprocess.check_output(['go', 'version'], text=True).strip().split()[2]

    # 交叉编译目标：未显式传参时回退到当前进程环境，再不济交给 go 自己判断。
    target_goos = goos or os.environ.get('GOOS', '')
    target_goarch = goarch or os.environ.get('GOARCH', '')

    # 输出文件名：默认本机 ./bookstark；指定平台时按 bookstark-<goos>-<goarch>[.exe]
    if not output:
        if target_goos or target_goarch:
            base = f'bookstark-{target_goos or "host"}-{target_goarch or "host"}'
            if target_goos == 'windows':
                base += '.exe'
            output = base
        else:
            output = 'bookstark'

    print('Building BookStark...')
    print(f'  commit: {commit or "none"}')
    print(f'  go:     {go_ver}')
    print(f'  time:   {built}')
    if target_goos or target_goarch:
        print(f'  target: {target_goos or "host"}/{target_goarch or "host"}')
    print(f'  output: {output}')

    # Scan static assets and compute content hashes
    print('  scanning static/ for assets...')
    assets, static_hash, file_hashes = scan_static_assets('static')
    count = patch_swjs('static/sw.js', static_hash, assets)
    print(f'  sw.js: {count} assets, static hash: {static_hash}')

    # Write asset-hashes.json for Go to load at runtime
    import json
    short_hashes = {k: v[:8] for k, v in file_hashes.items()}
    short_hashes['static/sw.js'] = static_hash[:8]
    hashes_path = os.path.join('static', 'asset-hashes.json')
    with open(hashes_path, 'w') as f:
        json.dump(short_hashes, f, indent=2)
    print(f'  asset-hashes.json: {len(short_hashes)} entries')

    # 输出目录如不存在先创建，便于产物直接落到 dist/
    out_dir = os.path.dirname(output)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    # Go build
    # -s -w 去掉符号表与 DWARF 调试信息，二进制可瘦身约 25%
    ldflags = f'-s -w -X main.buildTime={built} -X main.gitCommit={commit} -X main.goVersion={go_ver} -X main.assetHash={static_hash}'
    build_cmd = ['go', 'build', '-trimpath', '-ldflags', ldflags] + (extra_args or []) + ['-o', output, '.']
    print(f'  cmd: {" ".join(build_cmd)}')
    env = os.environ.copy()
    if target_goos:
        env['GOOS'] = target_goos
    if target_goarch:
        env['GOARCH'] = target_goarch
    # 纯 Go 依赖（modernc.org/sqlite），强制关闭 CGO，方便交叉编译。
    env.setdefault('CGO_ENABLED', '0')
    env.setdefault('GOFLAGS', '-p=1')
    env.setdefault('GOMAXPROCS', '1')
    env.setdefault('GOMEMLIMIT', '300MiB')
    subprocess.check_call(build_cmd, env=env)
    size = os.path.getsize(output)
    if size >= 1024 * 1024:
        size_str = f'{size / 1024 / 1024:.0f}M'
    else:
        size_str = f'{size / 1024:.0f}K'
    print(f'Done: {size_str}')

    # Kill old process and start (skip when --build / --output / --goos / --goarch 指定)
    if not build_only and not (output != 'bookstark' or target_goos or target_goarch):
        subprocess.run(['pkill', '-f', 'bookstark'], capture_output=True)
        os.execv('./bookstark', ['./bookstark', 'bookstark.db'])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Build BookStark')
    parser.add_argument('--build', action='store_true', dest='build_only',
                        help='Only build, do not kill/restart the process')
    parser.add_argument('--tags', dest='go_tags', default='',
                        help='Go build tags (e.g. timetzdata)')
    parser.add_argument('--goos', dest='goos', default='',
                        help='GOOS for cross-compile (linux/darwin/windows). Empty=host.')
    parser.add_argument('--goarch', dest='goarch', default='',
                        help='GOARCH for cross-compile (amd64/arm64). Empty=host.')
    parser.add_argument('--output', dest='output', default='',
                        help='Output binary path. Default: bookstark or bookstark-<goos>-<goarch>[.exe]')
    args = parser.parse_args()
    extra = []
    if args.go_tags:
        extra = ['-tags', args.go_tags]
    main(build_only=args.build_only,
         extra_args=extra if extra else None,
         output=args.output or None,
         goos=args.goos or None,
         goarch=args.goarch or None)
