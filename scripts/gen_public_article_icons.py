#!/usr/bin/env python3
"""Generate the article icon pool from bundled CSS and actual font glyphs.
Requires fonttools (with brotli support). Run with --check after updating fonts.
Brand icons are excluded because the project does not ship the brand font.
"""
import argparse
import hashlib
from pathlib import Path
import re
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / 'static/css/font-awesome.min.css'
FONTS = [('fa-solid', 'fa-solid-900.woff2'), ('fa-regular', 'fa-regular-400.woff2')]
DEST = ROOT / 'controllers/public_article_icons_generated.go'


def generate():
    css = CSS.read_text()
    rules = re.findall(r'((?:\.fa-[a-z0-9-]+:before,?)+)\{content:"\\([0-9a-f]+)"\}', css)
    icons = []
    sources = [CSS]
    for style, filename in FONTS:
        path = ROOT / 'static/webfonts' / filename
        sources.append(path)
        with TTFont(path) as font:
            cmap = font.getBestCmap()
            glyphs = {}
            for selectors, codepoint in rules:
                glyph = cmap.get(int(codepoint, 16))
                if glyph is None:
                    continue
                # CSS aliases share a glyph; include exactly one name per glyph/style.
                names = re.findall(r'\.(fa-[a-z0-9-]+):before', selectors)
                glyphs.setdefault(glyph, set()).update(names)
            icons.extend(style + ' ' + sorted(names)[0] for names in glyphs.values())
    lines = ['// Code generated by scripts/gen_public_article_icons.py; DO NOT EDIT.',
             '// Font Awesome Free 6.5.1: icons CC BY 4.0, fonts SIL OFL 1.1.',
             '// https://fontawesome.com/license/free']
    lines += ['// SHA256 ' + str(p.relative_to(ROOT)) + ': ' + hashlib.sha256(p.read_bytes()).hexdigest() for p in sources]
    lines += ['', 'package controllers', '', 'var publicArticleIcons = []string{']
    lines += ['\t"' + icon + '",' for icon in sorted(icons)]
    return '\n'.join(lines + ['}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not DEST.exists() or DEST.read_text() != output:
            raise SystemExit('Article icon catalog is stale; rerun this script.')
    else:
        DEST.write_text(output)
    print('Article icon catalog: %d supported glyph/style pairs' % output.count('\t"'))
