const previewOrigin=process.env.BOOKSTARK_VISUAL_URL||'http://127.0.0.1:8099';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || '/vol1/1000/wy/photos-apk-test/bookstark-flutter/browser-tools/node_modules/playwright-core');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/root/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome',args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(previewOrigin+'/',{waitUntil:'networkidle',timeout:60000});
  const accessibility=page.locator('flt-semantics-placeholder');
  if(await accessibility.count()) await accessibility.dispatchEvent('click');
  await page.getByText('知识库 · 笔记',{exact:true}).waitFor({timeout:30000});
  const out=process.env.SCREENSHOT_DIR || '/vol1/1000/wy/photos-apk-test/bookstark-flutter/screenshots';
  fs.mkdirSync(out,{recursive:true});
  await page.mouse.move(0,0);
  await page.waitForTimeout(350);
  await page.screenshot({path:out+'/07-notes-fixture-actual.png'});
  await page.getByRole('button',{name:/^私密阅读摘录/}).click();
  await page.getByText('解锁笔记',{exact:true}).waitFor();
  await page.mouse.move(0,0);
  await page.waitForTimeout(350);
  await page.screenshot({path:out+'/08-unlock-fixture-actual.png'});
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:/^阅读的意义/}).click();
  await page.getByText('发现未保存草稿',{exact:true}).waitFor();
  await page.mouse.move(0,0);
  await page.waitForTimeout(350);
  await page.screenshot({path:out+'/08-draft-recovery-fixture-actual.png'});
  await page.getByRole('button',{name:'恢复草稿',exact:true}).click();
  await page.getByText('草稿已保留 · 尚未提交',{exact:true}).waitFor();
  await page.mouse.move(0,0);
  await page.waitForTimeout(350);
  await page.screenshot({path:out+'/08-editor-fixture-actual.png'});
  await page.getByRole('button',{name:'预览',exact:true}).click();
  await page.waitForTimeout(350);
  assert.equal(await page.getByRole('button',{name:'加粗',exact:true}).count(),0,'edit toolbar must disappear in preview');
  await page.mouse.move(0,0);
  await page.waitForTimeout(350);
  await page.screenshot({path:out+'/08-markdown-preview-fixture-actual.png'});
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS isolated visual fixtures: list, password dialog, draft recovery, editor, Markdown preview; no page errors');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
