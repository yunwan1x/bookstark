const previewOrigin=process.env.BOOKSTARK_VISUAL_URL||'http://127.0.0.1:8099';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || '/vol1/1000/wy/photos-apk-test/bookstark-flutter/browser-tools/node_modules/playwright-core');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/root/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome',args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(previewOrigin+'/',{waitUntil:'networkidle',timeout:60000});
 const accessibility=page.locator('flt-semantics-placeholder');
 if(await accessibility.count())await accessibility.dispatchEvent('click');
 await page.getByRole('button',{name:/^阅读的意义/}).click();
 await page.getByRole('button',{name:'恢复草稿',exact:true}).click();
 const chooserPromise=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'插入图片',exact:true}).click();
 const chooser=await chooserPromise;
 await chooser.setFiles({name:'阅读摘录.png',mimeType:'image/png',buffer:fs.readFileSync('/vol1/1000/wy/bookstark/docs/flutter-rewrite/pages/08-editor.png')});
 await page.getByRole('button',{name:/阅读摘录\.png/}).first().waitFor();
 const out='/vol1/1000/wy/photos-apk-test/bookstark-flutter/screenshots';fs.mkdirSync(out,{recursive:true});
 await page.mouse.move(0,0);await page.waitForTimeout(350);
 await page.screenshot({path:out+'/08-attachment-selected-fixture-actual.png'});
 await page.getByRole('button',{name:'预览',exact:true}).click();
 await page.getByRole('img',{name:'阅读摘录.png',exact:true}).waitFor();
 assert.equal(await page.getByText('图片加载失败',{exact:true}).count(),0);
 assert.equal(await page.getByText('不支持的图片：阅读摘录.png',{exact:true}).count(),0);
 assert.equal(await page.getByRole('progressbar').count(),0);
 await page.mouse.move(0,0);
 await page.screenshot({path:out+'/08-attachment-preview-fixture-actual.png'});
 await page.getByRole('button',{name:'阅读摘录.png',exact:true}).click();
 await page.getByRole('button',{name:'关闭',exact:true}).waitFor();
 await page.mouse.move(0,0);await page.waitForTimeout(350);
 await page.screenshot({path:out+'/08-attachment-zoom-fixture-actual.png'});
 assert.equal(await page.getByRole('button',{name:'分享图片',exact:true}).count(),1);
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PASS browser file chooser -> production editor attachment insertion -> image preview; fixture storage, no page errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
